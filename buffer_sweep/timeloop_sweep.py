# Generalized evaluator: walk an arbitrary nest (our cost semantics)
# ----------------------------------------------------------------------------
def synthetic_nest(M, K, N, m, k, n, perm="MNK"):
    """v1-style single-tile nest: DRAM loops (perm outer->inner over tile
    counts), tiles (m,k,n) realized below the buffers. Dims must divide."""
    Mp, Kp, Np = bs.pad32(M), bs.pad32(K), bs.pad32(N)
    assert Mp % m == 0 and Kp % k == 0 and Np % n == 0, "synthetic nest needs divisors"
    counts = {"M": Mp // m, "K": Kp // k, "N": Np // n}
    return {
        "DRAM": [(d, counts[d]) for d in perm if counts[d] > 1],
        "w_buffer": [],
        "a_buffer": [],
        "o_buffer": [(d, f) for d, f in
                     (("M", m), ("K", k // 32), ("N", n // 32)) if f > 1],
    }


def eval_nest(levels, M, K, N, bw=None):
    """Score one mapping under OUR cost semantics. Returns the walk_gemm dict
    (reads/writes bits, fill, steady, drain, compute) -- see module docstring.

    Steps = one iteration of the temporal loops ABOVE o_buffer (loops at
    o_buffer + spatial live inside every operand's tile). All steps are uniform
    (Timeloop factorizes the padded dims exactly), so intervals collapse to
    closed-form demand segments."""
    bw = bs.EFF_BW if bw is None else bw
    Mp, Kp, Np = bs.pad32(M), bs.pad32(K), bs.pad32(N)
    dims = {"M": Mp, "K": Kp, "N": Np}
    # validate factorization: product over all levels + spatial == padded dims
    for d in "MKN":
        prod = SPATIAL.get(d, 1)
        for lv in LEVELS:
            for (dd, f) in levels[lv]:
                if dd == d:
                    prod *= f
        if prod != dims[d]:
            raise ValueError("nest does not factorize %s: %d != %d" % (d, prod, dims[d]))

    # operand tile sizes: product of its dims' factors at home level and below
    tile_bits = {}
    for op, (home, odims, obits) in OPERANDS.items():
        hi = LEVELS.index(home)
        elems = 1
        for d in odims:
            p = SPATIAL.get(d, 1)
            for lv in LEVELS[hi:]:
                for (dd, f) in levels[lv]:
                    if dd == d:
                        p *= f
            elems *= p
        tile_bits[op] = elems * obits

    # step loops = everything above o_buffer, outer -> inner
    step_loops = []              # (dim, factor, level_idx)
    for li, lv in enumerate(LEVELS[:3]):
        for (d, f) in levels[lv]:
            step_loops.append((d, f, li))
    T = 1
    for (_d, f, _li) in step_loops:
        T *= f
    macs_per_step = (Mp * Kp * Np) // T
    comp = bs.CYCLES_PER_BIT * bs.WBITS * macs_per_step / (bs.TILE * bs.TILE)
    compute = bs.CYCLES_PER_BIT * bs.WBITS * Mp * Kp * Np / (bs.TILE * bs.TILE)

    # id positions per operand: loops strictly ABOVE its home that project on it
    idpos = {}
    for op, (home, odims, _b) in OPERANDS.items():
        hi = LEVELS.index(home)
        idpos[op] = [i for i, (d, _f, li) in enumerate(step_loops)
                     if li < hi and d in odims]
    kpos = [i for i, (d, _f, _li) in enumerate(step_loops) if d == "K"]
    k_req = 1
    for i in kpos:
        k_req *= step_loops[i][1]

    # walk the odometer once, recording per-operand residency intervals
    coords = [0] * len(step_loops)
    intervals = {op: [] for op in OPERANDS}     # (start, oid)
    o_kseen = []                                # per O interval: set of k-coords
    prev = {op: None for op in OPERANDS}
    for t in range(T):
        for op in OPERANDS:
            oid = tuple(coords[i] for i in idpos[op])
            if oid != prev[op]:
                intervals[op].append([t, oid])
                if op == "O":
                    o_kseen.append(set())
                prev[op] = oid
        if kpos:
            o_kseen[-1].add(tuple(coords[i] for i in kpos))
        # increment odometer (innermost = last position fastest)
        for i in range(len(step_loops) - 1, -1, -1):
            coords[i] += 1
            if coords[i] < step_loops[i][1]:
                break
            coords[i] = 0
        else:
            pass                                # T exhausted anyway
    if not kpos:
        for s in o_kseen:
            s.add(())

    def lens(iv):
        return [(iv[i + 1][0] if i + 1 < len(iv) else T) - iv[i][0]
                for i in range(len(iv))]

    # O bookkeeping: spill (departs incomplete) / reload (arrives after spill)
    o_iv = intervals["O"]
    o_len = lens(o_iv)
    seen = {}
    spilled = set()
    reload_flag = [False] * len(o_iv)
    complete_flag = [False] * len(o_iv)
    for i, (_s, oid) in enumerate(o_iv):
        if oid in spilled:
            reload_flag[i] = True
        seen.setdefault(oid, set()).update(o_kseen[i])
        if len(seen[oid]) == k_req:
            complete_flag[i] = True             # departs complete (final write)
        else:
            spilled.add(oid)                    # departs partial (spill write)
    assert all(len(s) == k_req for s in seen.values()), "O accumulation incomplete"

    # traffic (bits)
    n_w, n_a, n_o = len(intervals["W"]), len(intervals["A"]), len(o_iv)
    n_reload = sum(reload_flag)
    reads = n_w * tile_bits["W"] + n_a * tile_bits["A"] + n_reload * tile_bits["O"]
    writes = n_o * tile_bits["O"]               # every departure writes (spill|final)

    # per-step DRAM demand, piecewise constant on merged interval segments:
    #   W/A: NEXT tile prefetch spread over the CURRENT tile's interval
    #   O:   predecessor drain + (spilled) successor reload over current interval
    def demands(op):
        iv, ln, out = intervals[op], lens(intervals[op]), []
        for i in range(len(iv)):
            if op == "O":
                bits = (tile_bits["O"] if i > 0 else 0.0) \
                     + (tile_bits["O"] if i + 1 < len(iv) and reload_flag[i + 1] else 0.0)
            else:
                bits = tile_bits[op] if i + 1 < len(iv) else 0.0
            out.append((iv[i][0], bits / ln[i]))
        return out                              # (start, demand_per_step)

    dmd = {op: demands(op) for op in OPERANDS}
    breakpoints = sorted({0, T} | {s for op in OPERANDS for (s, _d) in dmd[op]})
    ptr = {op: 0 for op in OPERANDS}
    steady = 0.0
    for bi in range(len(breakpoints) - 1):
        b0, b1 = breakpoints[bi], breakpoints[bi + 1]
        d = 0.0
        for op in OPERANDS:
            lst = dmd[op]
            while ptr[op] + 1 < len(lst) and lst[ptr[op] + 1][0] <= b0:
                ptr[op] += 1
            d += lst[ptr[op]][1]
        steady += max(0.0, d / bw - comp) * (b1 - b0)

    fill = (tile_bits["W"] + tile_bits["A"]) / bw
    drain = tile_bits["O"] / bw                 # last final write, nothing hides it
    return {"reads": float(reads), "writes": float(writes), "fill": fill,
            "steady": steady, "drain": drain, "compute": compute,
            "tile_bits": dict(tile_bits), "n_fetch": (n_w, n_a, n_o, n_reload)}


def rollup(M, K, N, r):
    """eval_nest result -> energy/cycles with the v1 coefficients (single source:
    same formulas as buffer_sweep.gemm_cost, generalized reads/writes)."""
    Mp, Kp, Np = bs.pad32(M), bs.pad32(K), bs.pad32(N)
    cubes = (Mp // bs.TILE) * (Kp // bs.TILE) * (Np // bs.TILE)
    dram = r["reads"] + r["writes"]
    onchip = r["reads"] + cubes * bs.TILE * bs.TILE * (bs.ABITS + bs.WBITS)
    mac = Mp * Kp * Np
    rmw = cubes * bs.TILE * bs.TILE
    energy = (dram * bs.C_DRAM + onchip * bs.C_ONCHIP
              + mac * bs.C_MAC + rmw * bs.C_RMW)
    cycles = r["compute"] + r["fill"] + r["steady"] + r["drain"]
    return {"energy": energy, "cycles": cycles, "dram_bits": dram,
            "steady": r["steady"]}


