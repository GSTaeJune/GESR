    """Job cache keyed by the mapper config: editing mapper_sweep.yaml starts a
    fresh cache subdir (stale results from other knobs are never mixed in)."""
    with open(os.path.join(TL_DIR, "mapper_sweep.yaml"), "rb") as f:
        tag = hashlib.md5(f.read().replace(b"\r\n", b"\n")).hexdigest()[:8]
    return os.path.join(HERE, "results", "tl_cache", "cfg_" + tag)


