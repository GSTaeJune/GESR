def selftest():
    n = 0
    # 1. v1 equivalence: O-stationary synthetic nest == buffer_sweep.walk_gemm
    #    (exact, divisor tiles, Kt >= 2 so every W/A interval is one step)
    for (M, K, N) in ((64, 64, 64), (128, 96, 64), (224, 192, 96)):
        for (m, k, nn) in ((32, 32, 32), (64, 32, 32), (32, 32, 64)):
            if M % m or K % k or N % nn or K // k < 2:
                continue
            for bw in (1.0, bs.EFF_BW, 1e9):
                a = bs.walk_gemm(M, K, N, m, k, nn, bw)
                b = eval_nest(synthetic_nest(M, K, N, m, k, nn), M, K, N, bw)
                for key in ("fill", "steady", "drain", "compute"):
                    assert math.isclose(a[key], b[key], rel_tol=1e-9, abs_tol=1e-6), \
                        (key, M, K, N, m, k, nn, bw, a[key], b[key])
                assert math.isclose(a["reads"], b["reads"]) \
                    and math.isclose(a["writes"], b["writes"])
                n += 1
    # 2. Kt == 1 corner: traffic identical; new interval-spread stall <= v1's
    for bw in (1.0, bs.EFF_BW):
        a = bs.walk_gemm(96, 64, 128, 32, 64, 32, bw)
        b = eval_nest(synthetic_nest(96, 64, 128, 32, 64, 32), 96, 64, 128, bw)
        assert math.isclose(a["reads"], b["reads"]) and math.isclose(a["writes"], b["writes"])
        assert b["steady"] <= a["steady"] + 1e-9
        n += 1
    # 3. psum spill hand-check: K OUTERMOST at DRAM forces spill+reload
    lv = {"DRAM": [("K", 2), ("M", 2), ("N", 2)], "w_buffer": [],
          "a_buffer": [], "o_buffer": [("M", 32)]}    # tiles 32x32x32
    r = eval_nest(lv, 64, 64, 64, bw=1e9)
    tw, ta, to = 32 * 32 * bs.WBITS, 32 * 32 * bs.ABITS, 32 * 32 * bs.OBITS
    assert r["n_fetch"] == (4, 8, 8, 4), r["n_fetch"]   # W ivs, A ivs, O ivs, reloads
    assert r["reads"] == 4 * tw + 8 * ta + 4 * to
    assert r["writes"] == 8 * to                        # 4 spills + 4 finals
    assert r["steady"] == 0.0                           # bw=1e9 hides everything
    n += 1
    # 4. smoke-run mapping reproduction (skipped if output/ not present locally)
    smoke = os.path.join(TL_DIR, "output", "timeloop-mapper.map.yaml")
    if os.path.isfile(smoke):
        with open(smoke) as f:
            levels = parse_map_yaml(f.read())
        r = eval_nest(levels, 224, 192, 768)
        # Timeloop's own element counts for this mapping (NOTES.md section b):
        assert r["reads"] == (43008 + 7 * 147456) * 8, r["reads"]
        assert r["writes"] == 172032 * 32
        assert r["steady"] == 0.0                       # interval-spread hides all
        with open(os.path.join(TL_DIR, "output", "timeloop-mapper.stats.txt")) as f:
            assert parse_stats(f.read()) == (32256, 321.03)
        n += 1
    print("timeloop_sweep selftest OK (%d checks)" % n)
    return 0


