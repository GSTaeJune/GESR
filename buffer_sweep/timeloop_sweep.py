def model_shapes(model):
    """Aggregate a model's per-layer GEMMs into {(Mp,Kp,Np): weight}."""
    spec = bs.MODELS[model]
    out = {}
    for (_g, M, K, N, cnt) in spec["gemms"]:
        key = (bs.pad32(M), bs.pad32(K), bs.pad32(N))
        out[key] = out.get(key, 0) + cnt * spec["layers"]
    return out


def partitions(cap_kb, slices=SLICES):
    """Split the per-copy budget (cap/2, ping-pong) into (W,A,O) bit triples on
    a slices-grid, each >= 1 slice. Returns [(w_bits, a_bits, o_bits), ...]."""
    half = cap_kb * 1024 * 8 // 2
    assert half % slices == 0
    unit = half // slices
    out = []
    for wi in range(1, slices - 1):
        for ai in range(1, slices - wi):
            oi = slices - wi - ai
            out.append((wi * unit, ai * unit, oi * unit))
    return out


def job_key(shape, part):
    (M, K, N), (wb, ab, ob) = shape, part
    return "M%dK%dN%d_w%d_a%d_o%d" % (M, K, N, wb // 8, ab // 8, ob // 32)


def gen_jobs(models, caps, slices):
    """Write arch/problem YAMLs for every missing (partition, shape) job."""
    os.makedirs(CACHE_DIR, exist_ok=True)
    keys = set()
    for cap in caps:
        for part in partitions(cap, slices):
            for model in models:
                for shape in model_shapes(model):
                    keys.add((shape, part))
    n_new = 0
    for (shape, part) in sorted(keys):
        key = job_key(shape, part)
        d = os.path.join(CACHE_DIR, key)
        if os.path.isdir(d):
            continue
        os.makedirs(d)
        (M, K, N), (wb, ab, ob) = shape, part
        with open(os.path.join(d, "arch.yaml"), "w", newline="\n") as f:
            f.write(ARCH_TEMPLATE.format(w_depth=wb // 8, a_depth=ab // 8,
                                         o_depth=ob // 32))
        with open(os.path.join(d, "problem.yaml"), "w", newline="\n") as f:
            f.write(PROBLEM_TEMPLATE.format(M=M, K=K, N=N))
        n_new += 1
    print("gen_jobs: %d total, %d newly generated" % (len(keys), n_new))
    return len(keys)


def to_wsl(path):
    p = os.path.abspath(path).replace("\\", "/")
    return "/mnt/" + p[0].lower() + p[2:]


def run_jobs(jobs=JOBS, deadline=240):
    """One blocking WSL call that runs every pending job (parallel inside)."""
    cmd = "%s %s %d %d" % (to_wsl(os.path.join(TL_DIR, "run_jobs.sh")),
                           to_wsl(CACHE_DIR), jobs, deadline)
    print("run_jobs: wsl bash -lc '%s'" % cmd)
    r = subprocess.run(["wsl", "bash", "-lc", cmd])
    if r.returncode != 0:
        raise RuntimeError("run_jobs.sh failed (exit %d)" % r.returncode)


def load_job(shape, part):
    """Cached mapper result -> (levels, tl_cycles, tl_energy_uj) or None if the
    mapper found no valid mapping for this partition."""
    d = os.path.join(CACHE_DIR, job_key(shape, part))
    if os.path.isfile(os.path.join(d, "INVALID")):
        return None
    with open(os.path.join(d, "map.yaml")) as f:
        levels = parse_map_yaml(f.read())
    with open(os.path.join(d, "stats.txt")) as f:
        tl_cyc, tl_uj = parse_stats(f.read())
    return levels, tl_cyc, tl_uj


# ----------------------------------------------------------------------------
# v1 baseline: best O-stationary (m,k,n) under the same partition
# ----------------------------------------------------------------------------
_V1_MEMO = {}


def v1_best(model, part):
    """Best v1 (grouped, O-stationary) energy/cycles fitting (w,a,o) bit caps.
    v1 semantics (residual tiles allowed; Kt==1 stall charged conservatively)."""
    wb, ab, ob = part
    shapes = model_shapes(model)
    max_m = max(M for (M, _K, _N) in shapes)
    max_k = max(K for (_M, K, _N) in shapes)
    max_n = max(N for (_M, _K, N) in shapes)
    best = None
    m = bs.TILE
    while m <= max_m and bs.WBITS * m * bs.TILE <= wb and bs.OBITS * m * bs.TILE <= ob:
        k = bs.TILE
        while k <= max_k and bs.WBITS * m * k <= wb and bs.ABITS * k * bs.TILE <= ab:
            n = bs.TILE
            while (n <= max_n and bs.ABITS * k * n <= ab
                   and bs.OBITS * m * n <= ob):
                tot_e = tot_c = 0.0
                for (M, K, N), wgt in shapes.items():
                    ck = (M, K, N, m, k, n)
                    c = _V1_MEMO.get(ck)
                    if c is None:
                        c = bs.gemm_cost(M, K, N, m, k, n)
                        _V1_MEMO[ck] = c
                    tot_e += c["energy"] * wgt
                    tot_c += c["cycles"] * wgt
                if best is None or (tot_e, tot_c) < (best[0], best[1]):
                    best = (tot_e, tot_c, m, k, n)
                n += bs.TILE
            k += bs.TILE
        m += bs.TILE
    return best          # None if nothing fits


# ----------------------------------------------------------------------------
# Scoring + outputs
# ----------------------------------------------------------------------------
def score(models, caps, slices, top=5):
    os.makedirs(OUT_DIR, exist_ok=True)
    all_rows = []
    for model in models:
        shapes = model_shapes(model)
        rows = []
        details = []
        for cap in caps:
            for part in partitions(cap, slices):
                wb, ab, ob = part
                tot = {"energy": 0.0, "cycles": 0.0, "dram_bits": 0.0,
                       "steady": 0.0, "tl_cycles": 0.0, "tl_uj": 0.0}
                bad = None
                for shape, wgt in sorted(shapes.items()):
                    job = load_job(shape, part)
                    if job is None:
                        bad = shape
                        break
                    levels, tl_cyc, tl_uj = job
                    M, K, N = shape
                    r = rollup(M, K, N, eval_nest(levels, M, K, N))
                    for kk in ("energy", "cycles", "dram_bits", "steady"):
                        tot[kk] += r[kk] * wgt
                    tot["tl_cycles"] += tl_cyc * wgt
                    tot["tl_uj"] += tl_uj * wgt
                    details.append({
                        "model": model, "cap_kb": cap,
                        "w_kb": wb * 2 // 8192, "a_kb": ab * 2 // 8192,
                        "o_kb": ob * 2 // 8192,
                        "shape": "%dx%dx%d" % shape, "weight": wgt,
                        "nest": nest_str(levels),
                        "energy_pj": r["energy"], "cycles": r["cycles"],
                        "tl_cycles": tl_cyc, "tl_energy_uj": tl_uj,
                    })
                v1 = v1_best(model, part)
                row = {
                    "model": model, "cap_kb": cap,
                    "w_kb": wb * 2 // 8192, "a_kb": ab * 2 // 8192,
                    "o_kb": ob * 2 // 8192,          # physical KB incl. ping-pong
                    "feasible": bad is None,
                    "energy_pj": tot["energy"] if bad is None else math.nan,
                    "cycles": tot["cycles"] if bad is None else math.nan,
                    "steady_stall": tot["steady"] if bad is None else math.nan,
                    "tl_cycles_sum": tot["tl_cycles"] if bad is None else math.nan,
                    "tl_energy_uj_sum": tot["tl_uj"] if bad is None else math.nan,
                    "v1_energy_pj": v1[0] if v1 else math.nan,
                    "v1_cycles": v1[1] if v1 else math.nan,
                    "v1_mkn": ("%d/%d/%d" % (v1[2], v1[3], v1[4])) if v1 else "",
                    "fail_shape": ("%dx%dx%d" % bad) if bad else "",
                }
                # best known = min(timeloop-proposed, v1 floor), per metric
                cands = []
                if bad is None:
                    cands.append(("tl", tot["energy"], tot["cycles"]))
                if v1:
                    cands.append(("v1", v1[0], v1[1]))
                if cands:
                    be = min(cands, key=lambda c: c[1])
                    bc = min(cands, key=lambda c: c[2])
                    row.update(best_energy_pj=be[1], best_energy_src=be[0],
                               best_cycles=bc[2], best_cycles_src=bc[0])
                    row["feasible"] = True       # at least one scheduler fits
                else:
                    row.update(best_energy_pj=math.nan, best_energy_src="",
                               best_cycles=math.nan, best_cycles_src="")
                rows.append(row)
        all_rows += rows
        _write_csv(rows, os.path.join(OUT_DIR, "%s.csv" % model))
        _write_csv(details, os.path.join(OUT_DIR, "%s_details.csv" % model))
        _console(rows, model, caps, top)
        for cap in caps:
            for metric, tag in (("best_energy_pj", "energy"), ("best_cycles", "cycles")):
                _plot_partition_heatmap(
                    rows, model, cap, metric, slices,
                    os.path.join(OUT_DIR, "%s_cap%d_%s.png" % (model, cap, tag)))
    for metric, tag in (("best_energy_pj", "energy"), ("best_cycles", "cycles")):
        _plot_summary(all_rows, caps, metric,
                      os.path.join(OUT_DIR, "summary_%s.png" % tag))
    print("score: wrote CSVs and plots to %s" % OUT_DIR)
    return all_rows


def _write_csv(rows, path):
    if not rows:
        return
    with open(path, "w", newline="") as f:
        wr = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        wr.writeheader()
        wr.writerows(rows)


def _console(rows, model, caps, top):
    for cap in caps:
        sub = [r for r in rows if r["cap_kb"] == cap and r["feasible"]]
        n_all = sum(1 for r in rows if r["cap_kb"] == cap)
        print("%s  cap=%dKB  (%d/%d partitions feasible)"
              % (model, cap, len(sub), n_all))
        if not sub:
            continue
        sub.sort(key=lambda r: (r["best_energy_pj"], r["best_cycles"]))
        print("  %5s %5s %5s %13s %12s %4s %13s %13s"
              % ("W/KB", "A/KB", "O/KB", "best_E(uJ)", "best_cyc(M)", "src",
                 "tl_E(uJ)", "v1_E(uJ)"))
        for r in sub[:top]:
            def _uj(x):
                return (x / 1e6) if not math.isnan(x) else float("nan")
            print("  %5d %5d %5d %13.3f %12.3f %4s %13.3f %13.3f"
                  % (r["w_kb"], r["a_kb"], r["o_kb"],
                     r["best_energy_pj"] / 1e6, r["best_cycles"] / 1e6,
                     r["best_energy_src"], _uj(r["energy_pj"]),
                     _uj(r["v1_energy_pj"])))
        byc = min(sub, key=lambda r: (r["best_cycles"], r["best_energy_pj"]))
        print("  best-by-cycles: W=%d A=%d O=%d KB  cycles=%.3fM (src=%s)  energy=%.3fuJ\n"
              % (byc["w_kb"], byc["a_kb"], byc["o_kb"],
                 byc["best_cycles"] / 1e6, byc["best_cycles_src"],
                 byc["best_energy_pj"] / 1e6))


def _plot_partition_heatmap(rows, model, cap, metric, slices, out_path):
    plt = bs._plt()
    sub = [r for r in rows if r["cap_kb"] == cap and r["feasible"]]
    if plt is None or not sub:
        return False
    unit_kb = cap / slices
    grid = [[math.nan] * (slices - 1) for _ in range(slices - 1)]
    for r in sub:
        wi = int(round(r["w_kb"] / unit_kb)) - 1
        ai = int(round(r["a_kb"] / unit_kb)) - 1
        grid[wi][ai] = r[metric]
    best = min(sub, key=lambda r: r[metric])
    fig, ax = plt.subplots(figsize=(5.5, 4.5))
    im = ax.imshow(grid, origin="lower", aspect="auto",
                   extent=[unit_kb / 2, cap - unit_kb / 2,
                           unit_kb / 2, cap - unit_kb / 2])
    ax.plot(best["a_kb"], best["w_kb"], "r*", markersize=15)
    ax.set_xlabel("A space (KB, incl. ping-pong)")
    ax.set_ylabel("W space (KB, incl. ping-pong)")
    ax.set_title("%s cap=%dKB %s (star: W=%d A=%d O=%d)"
                 % (model, cap, metric, best["w_kb"], best["a_kb"], best["o_kb"]))
    fig.colorbar(im, ax=ax, shrink=0.85)
    fig.tight_layout()
    fig.savefig(out_path, dpi=110)
    plt.close(fig)
    return True


def _plot_summary(all_rows, caps, metric, out_path):
    plt = bs._plt()
    if plt is None or not all_rows:
        return False
    fig, ax = plt.subplots(figsize=(6.5, 4.5))
    v1_metric = {"best_energy_pj": "v1_energy_pj", "best_cycles": "v1_cycles"}[metric]
    plotted = False
    for model in sorted({r["model"] for r in all_rows}):
        xs, ys, yv = [], [], []
        for cap in caps:
            sub = [r for r in all_rows
                   if r["model"] == model and r["cap_kb"] == cap and r["feasible"]]
            if sub:
                xs.append(cap)
                ys.append(min(r[metric] for r in sub))
                vv = [r[v1_metric] for r in sub if not math.isnan(r[v1_metric])]
                yv.append(min(vv) if vv else math.nan)
        if not xs:
            continue                        # no feasible partition anywhere
        plotted = True
        line, = ax.plot(xs, ys, marker="o", label=model + " (best known)")
        vpts = [(x, v) for x, v in zip(xs, yv) if not math.isnan(v)]
        if vpts:
            ax.plot([x for x, _v in vpts], [v for _x, v in vpts], marker="x",
                    linestyle="--", color=line.get_color(), alpha=0.6,
                    label=model + " (v1 fixed)")
    if not plotted:
        plt.close(fig)
        return False
    ax.set_xlabel("SRAM cap (KB, incl. ping-pong)")
    ax.set_ylabel("best " + metric)
    ax.set_yscale("log")
    ax.set_xscale("log", base=2)
    ax.legend(fontsize=7)
    ax.grid(True, which="both", alpha=0.3)
    fig.tight_layout()
    fig.savefig(out_path, dpi=110)
    plt.close(fig)
    return True


