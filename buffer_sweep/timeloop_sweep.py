# buffer_sweep/timeloop_sweep.py
"""Timeloop-scheduled SRAM partition sweep.

Division of labor (spec: docs/superpowers/specs/2026-07-06-timeloop-sweep-design.md):
  * WE sweep the architecture DOF: how the SRAM cap is partitioned into the
    W / A / O dedicated spaces (each ping-pong x2, so the mapper sees half).
  * TIMELOOP (WSL, timeloop-mapper) searches the schedule per (partition, GEMM):
    tile sizes + loop permutation, quantized by the 32x32 spatial SA.
  * OUR evaluator scores the returned mapping for the FINAL numbers: bit-serial
    timing (x WBITS), ping-pong prefetch windows, psum spill/reload, and the
    project energy coefficients. Timeloop's internal EDP only ranks its search.

Pipeline (all idempotent, disk-cached under results/tl_cache/):
  gen   -> write arch.yaml+problem.yaml per missing (partition, GEMM-shape) job
  run   -> one WSL call: timeloop/run_jobs.sh runs all pending jobs in parallel
  score -> parse map.yaml per job, eval with eval_nest(), aggregate per model,
           write CSV + heatmaps + summary plots under results/timeloop/

eval_nest() generalizes buffer_sweep.walk_gemm to an arbitrary Timeloop loop
nest: per-operand tiles can differ (multi-level M splits etc.), O tiles may be
evicted mid-accumulation (spill 32b + reload 32b), and each operand's next-tile
prefetch is spread over the CURRENT tile's residency interval (the shadow copy
is free for exactly that long). For the v1 O-stationary nest this reduces
EXACTLY to walk_gemm (asserted by --selftest); the one deliberate difference is
v1's Kt==1 corner, where v1 conservatively charged the whole W fetch to a
single step window (new model spreads it; selftest asserts traffic equal and
new steady <= v1 steady).

Usage:
  python timeloop_sweep.py --selftest
  python timeloop_sweep.py --quick               # deit_tiny x 64KB x few partitions
  python timeloop_sweep.py                       # full: all models x 64/128/256KB
  python timeloop_sweep.py --score-only          # skip mapper, score cached jobs
"""
