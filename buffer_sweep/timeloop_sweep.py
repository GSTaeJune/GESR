def main(argv=None):
    p = argparse.ArgumentParser(description="Timeloop-scheduled SRAM partition sweep")
    p.add_argument("--models", default="all")
    p.add_argument("--caps", default="64,128,256")
    p.add_argument("--slices", type=int, default=SLICES)
    p.add_argument("--jobs", type=int, default=JOBS)
    p.add_argument("--deadline", type=int, default=240,
                   help="per-job mapper wall-clock (s); SIGINT dumps best-so-far")
    p.add_argument("--score-only", action="store_true",
                   help="skip the WSL mapper stage; score cached jobs only")
    p.add_argument("--quick", action="store_true",
                   help="deit_tiny x 64KB x 4 slices (pipeline smoke)")
    p.add_argument("--selftest", action="store_true")
    a = p.parse_args(argv)
    if a.selftest:
        return selftest()

    models = sorted(bs.MODELS) if a.models == "all" else a.models.split(",")
    for m in models:
        if m not in bs.MODELS:
            p.error("unknown model %r" % m)
    try:
        caps = [int(x) for x in a.caps.split(",")]
    except ValueError as e:
        p.error("--caps must be comma-separated integers (%s)" % e)
    slices = a.slices
    if a.quick:
        models, caps, slices = ["deit_tiny"], [64], 4

    gen_jobs(models, caps, slices)
    if not a.score_only:
        run_jobs(a.jobs, a.deadline)
    score(models, caps, slices)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
