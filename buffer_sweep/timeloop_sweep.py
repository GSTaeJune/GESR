# ----------------------------------------------------------------------------
# map.yaml mini-parser (stdlib only -- no yaml module needed for this shape)
# ----------------------------------------------------------------------------
def parse_map_yaml(text):
    """Return {level: [(dim, factor), ...] outer->inner} for the temporal loops
    of the four LEVELS. map.yaml lists `permutation` INNERMOST-FIRST and
    `factors: M4 N1 K6`; unit factors are placeholders and dropped."""
    entries = {}
    cur = None
    for line in text.splitlines():
        s = line.strip()
        m = re.match(r"- target: (\w+)", s)
        if m:
            cur = {"target": m.group(1), "type": None, "factors": None, "perm": None}
            continue
        if cur is None:
            continue
        m = re.match(r"type: (\w+)", s)
        if m:
            cur["type"] = m.group(1)
        m = re.match(r"factors: (.+)", s)
        if m:
            cur["factors"] = m.group(1).strip()
        m = re.match(r"permutation: (\w+)", s)
        if m:
            cur["perm"] = m.group(1).strip()
        if cur["type"] and (cur["type"] == "datatype" or (cur["factors"] and cur["perm"])):
            if cur["type"] in ("temporal", "spatial"):
                entries[(cur["target"], cur["type"])] = (cur["factors"], cur["perm"])
            cur = None if cur["type"] != "datatype" else cur  # datatype: wait for end
    levels = {}
    for lv in LEVELS:
        fac, perm = entries.get((lv, "temporal"), ("M1 N1 K1", "MNK"))
        fmap = {}
        for tok in fac.split():
            fmap[tok[0]] = int(tok[1:])
        loops = [(d, fmap.get(d, 1)) for d in reversed(perm)]   # outer -> inner
        levels[lv] = [(d, f) for (d, f) in loops if f > 1]
    # spatial sanity: the SA constraint must have been respected
    fac, _perm = entries.get(("inter_PE_spatial", "spatial"), (None, None))
    if fac:
        sfac = {tok[0]: int(tok[1:]) for tok in fac.split()}
        if sfac.get("K", 1) != 32 or sfac.get("N", 1) != 32:
            raise ValueError("mapping violates 32x32 spatial constraint: %s" % fac)
    return levels


def nest_str(levels):
    """Compact one-line nest for CSV/console, e.g. 'DRAM:M7 | w:N24 | a:M8 | o:M4.K6'."""
    tag = {"DRAM": "DRAM", "w_buffer": "w", "a_buffer": "a", "o_buffer": "o"}
    parts = []
    for lv in LEVELS:
        if levels[lv]:
            parts.append(tag[lv] + ":" + ".".join("%s%d" % (d, f) for d, f in levels[lv]))
    return " | ".join(parts) if parts else "(all-resident)"


def parse_stats(text):
    """Timeloop's own Summary Stats -> (cycles, energy_uJ). Sanity columns only."""
    cyc = re.search(r"^Cycles: (\d+)", text, re.M)
    en = re.search(r"^Energy: ([0-9.eE+-]+) uJ", text, re.M)
    if not cyc or not en:
        raise ValueError("could not parse Summary Stats")
    return int(cyc.group(1)), float(en.group(1))


